const test = require('node:test');
const assert = require('node:assert/strict');
const path = require('node:path');
const mongoose = require('mongoose');
const jwt = require('jsonwebtoken');
const { MongoMemoryReplSet } = require('mongodb-memory-server');
const User = require('../src/models/User');
const IAR = require('../src/models/InspectionAcceptanceReport');
const RIS = require('../src/models/RequisitionIssueSlip');
const Inventory = require('../src/models/Inventory');
const Setting = require('../src/models/Setting');

test('IAR fund flows through item autocomplete, RIS save and issued forms', { timeout: 90000 }, async t => {
  const database = await MongoMemoryReplSet.create({ replSet: { count: 1 }, binary: { systemBinary: path.resolve(__dirname, '../node_modules/.cache/mongodb-memory-server/mongod-x64-win32-8.2.6.exe') } });
  await mongoose.connect(database.getUri());
  await Setting.create({ entityName: 'LGU Carigara' });
  await Promise.all([IAR.init(), RIS.init(), Inventory.init()]);
  const admin = await User.create({ firstName: 'Admin', lastName: 'Tester', email: 'fund-admin@example.test', username: 'fund-admin', password: 'test', office: 'Supply Office', division: 'Supply', role: 'admin' });
  const user = await User.create({ firstName: 'Account', lastName: 'User', email: 'fund-user@example.test', username: 'fund-user', password: 'test', office: 'Treasury', division: 'Finance', role: 'user', permissions: ['canViewRIS'] });
  const server = require('../src/app').listen(0);
  t.after(async () => { await new Promise(resolve => server.close(resolve)); await mongoose.disconnect(); await database.stop(); });
  const request = async (route, body, method = body ? 'POST' : 'GET') => {
    const response = await fetch(`http://127.0.0.1:${server.address().port}/api${route}`, { method, headers: { Authorization: `Bearer ${jwt.sign({ id: admin._id }, process.env.JWT_SECRET || 'dev-secret')}`, 'Content-Type': 'application/json' }, body: body ? JSON.stringify(body) : undefined });
    return { status: response.status, body: await response.json() };
  };
  const person = { name: 'Admin Tester', designation: 'Supply Officer', date: '2026-10-17' };
  const receive = async (iarNumber, name, stockNumber, fundCluster, responsibilityCenterCode = 'RCC-1') => {
    const result = await request('/iar', { iarNumber, entityName: 'LGU Carigara', fundCluster, supplierName: 'Supplier', poNumber: 'PO-1', poDate: '2026-10-17', responsibilityCenterCode, iarDate: '2026-10-17', invoiceNumber: 'INV-1', invoiceDate: '2026-10-17', inspectionDate: '2026-10-17', inspectedBy: 'Inspector', acceptanceDate: '2026-10-17', custodian: 'Custodian', items: [{ stockPropertyNumber: stockNumber, propertyPlantAndEquipment: name, description: `${name} specification`, unit: 'pcs', quantity: 1, unitCost: 1000, itemType: 'ASSET' }] });
    assert.equal(result.status, 201, JSON.stringify(result.body));
  };
  await receive('001', 'Printer', 'PR-1', 'General Fund');
  await receive('002', 'Broom', 'BR-1', 'Trust Fund', 'RCC-2');
  await receive('003', 'Printer', 'PR-1', 'Trust Fund', 'RCC-3');
  const available = await request('/ris/request-items');
  assert.equal(available.status, 200);
  const printer = available.body.data.find(item => item.stockNumber === 'PR-1');
  assert.deepEqual(new Set(printer.units.map(unit => unit.fundCluster)), new Set(['General Fund', 'Trust Fund']));
  const { createRisRow, risItemChoices, selectRisItem, risSelectedFunds, risSelectedCenters, setRisRequestedQuantity } = await import('../../frontend/src/utils/risItemSelection.js');
  const choices = risItemChoices(available.body.data, [createRisRow()], 0);
  const printerChoice = choices.find(choice => choice.name === 'Printer');
  let row = selectRisItem(createRisRow(), printerChoice);
  assert.equal(row.fundCluster, 'General Fund');
  assert.equal(row.responsibilityCenterCode, 'RCC-1');
  assert.deepEqual(risSelectedCenters([row], available.body.data), ['RCC-1']);
  row = setRisRequestedQuantity(row, '1', 1);
  assert.deepEqual(risSelectedFunds([row], available.body.data), ['General Fund']);
  assert.equal(risItemChoices(available.body.data, [row, createRisRow()], 1).some(choice => choice.name === 'Broom'), false);
  const recipient = { ...person, user: String(user._id), name: 'Account User', designation: 'Treasury' };
  const payload = { entityName: 'LGU Carigara', fundCluster: 'Wrong Fund', office: 'Treasury', responsibilityCenterCode: 'Wrong RCC', date: '2026-10-17', requestedBy: recipient, approvedBy: person, issuedBy: person, receivedBy: recipient, items: [row] };
  const saved = await request('/ris', payload);
  assert.equal(saved.status, 201, JSON.stringify(saved.body));
  assert.equal(saved.body.data.fundCluster, 'General Fund', 'Server ignores a stale or forged header fund');
  assert.equal(saved.body.data.responsibilityCenterCode, 'RCC-1', 'Responsibility code comes from the exact unit receipt');
  const broom = selectRisItem(createRisRow(), choices.find(choice => choice.name === 'Broom'));
  const mixed = await request('/ris', { ...payload, items: [row, setRisRequestedQuantity(broom, '1', 1)] });
  assert.equal(mixed.status, 400);
  assert.match(mixed.body.message, /different Fund Clusters/);
  await RIS.updateOne({ _id: saved.body.data._id }, { $set: { fundCluster: 'Stale fund' } });
  const issued = await request(`/ris/${saved.body.data._id}/approve`, {});
  assert.equal(issued.status, 200, JSON.stringify(issued.body));
  const record = await RIS.findById(saved.body.data._id);
  assert.equal(record.fundCluster, 'General Fund');
  assert.equal(record.responsibilityCenterCode, 'RCC-1');
  const ics = await require('../src/models/InventoryCustodianSlip').findById(record.inventoryCustodianSlip);
  assert.equal(ics.fundCluster, 'General Fund');
});
