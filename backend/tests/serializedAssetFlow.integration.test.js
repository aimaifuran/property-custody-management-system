const test = require('node:test');
const assert = require('node:assert/strict');
const path = require('node:path');
const mongoose = require('mongoose');
const jwt = require('jsonwebtoken');
const { MongoMemoryReplSet } = require('mongodb-memory-server');
const IAR = require('../src/models/InspectionAcceptanceReport');
const Inventory = require('../src/models/Inventory');
const Property = require('../src/models/Property');
const RIS = require('../src/models/RequisitionIssueSlip');
const PAR = require('../src/models/PropertyAcknowledgementReceipt');
const Card = require('../src/models/PropertyCard');
const User = require('../src/models/User');
const Setting = require('../src/models/Setting');
const PTR = require('../src/models/PropertyTransferReport');
const Accountability = require('../src/models/PropertyAccountability');
const issueRis = require('../src/utils/issueRis');

test('serialized assets keep exact unit and property identity from receipt through issuance and transfer', { timeout: 90000 }, async t => {
  const database = await MongoMemoryReplSet.create({ replSet: { count: 1 }, binary: { systemBinary: path.resolve(__dirname, '../node_modules/.cache/mongodb-memory-server/mongod-x64-win32-8.2.6.exe') } });
  await mongoose.connect(database.getUri());
  await Promise.all([IAR, Inventory, Property, RIS, PAR, Card].map(Model => Model.init()));
  await Setting.create({ entityName: 'LGU' });
  const server = require('../src/app').listen(0);
  t.after(async () => { server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); await mongoose.disconnect(); await database.stop(); });
  const makeUser = (name, role) => User.create({ username: name, firstName: name, lastName: 'Test', email: `${name}@example.test`, password: 'test', office: 'Treasury', division: 'Finance', role, permissions: ['canViewRIS'] });
  const admin = await makeUser('admin', 'admin');
  const recipient = await makeUser('recipient', 'user');
  const receiver = await makeUser('receiver', 'user');
  const request = async (url, body, actor = admin, method = 'POST') => {
    const response = await fetch(`http://127.0.0.1:${server.address().port}/api${url}`, { method, headers: { Authorization: `Bearer ${jwt.sign({ id: actor._id }, process.env.JWT_SECRET || 'dev-secret')}`, 'Content-Type': 'application/json' }, ...(body ? { body: JSON.stringify(body) } : {}) });
    return { status: response.status, body: await response.json() };
  };
  const payload = { entityName: 'LGU', fundCluster: 'General Fund', supplierName: 'Supplier', poNumber: 'PO-1', poDate: '2026-10-14', responsibilityCenterCode: 'Supply', iarNumber: '1001', iarDate: '2026-10-14', invoiceNumber: 'INV-1', invoiceDate: '2026-10-14', inspectionDate: '2026-10-14', inspectedBy: 'Inspector', acceptanceDate: '2026-10-14', custodian: 'Custodian', items: [
    { stockPropertyNumber: 'LAPTOP', propertyPlantAndEquipment: 'IT Equipment', description: 'Laptop A', serialNumber: 'SN-A', quantity: 1, unit: 'unit', unitCost: 45000 },
    { stockPropertyNumber: 'LAPTOP', propertyPlantAndEquipment: 'IT Equipment', description: 'Laptop B', serialNumber: 'SN-B', quantity: 1, unit: 'unit', unitCost: 60000 },
  ] };
  const saved = await request('/iar', payload);
  assert.equal(saved.status, 201, JSON.stringify(saved.body));
  const iar = saved.body.data;
  const units = await Inventory.find({ inspectionAcceptanceReport: iar._id }).sort({ serialNumber: 1 });
  assert.equal(units.length, 2);
  assert.ok(units.every(unit => unit.property));
  assert.notEqual(String(units[0].property), String(units[1].property));
  assert.equal((await Property.findById(units[1].property)).serialNumber, 'SN-B-1');
  assert.match((await Card.findOne({ iar: iar._id })).serialNumber, /SN-A-1; SN-B-1/);
  const draft = await RIS.findOne({ iar: iar._id });
  assert.equal(draft, null, 'Receiving stock never creates a RIS request');
  const requestableUnits = async () => {
    const response = await request('/ris/request-items', undefined, admin, 'GET');
    assert.equal(response.status, 200, JSON.stringify(response.body));
    return response.body.data.flatMap(item => item.units);
  };
  assert.deepEqual(new Set((await requestableUnits()).map(unit => unit.serialNumber)), new Set(['SN-A-1', 'SN-B-1']));
  const makeRis = (number, inventory) => RIS.create({ risNumber: number, entityName: 'LGU', fundCluster: 'General Fund', office: 'Treasury', status: 'APPROVED', requestedBy: { user: recipient._id, name: 'recipient Test' }, items: [{ stockNumber: 'LAPTOP', description: 'Laptop', quantityRequested: 1, quantityIssued: 1, inventory }] });
  const unspecified = await makeRis('RIS-UNSPECIFIED');
  await assert.rejects(issueRis(unspecified._id, admin), /Select the exact asset unit/);
  const ris = await makeRis('RIS-SELECTED', units[1]._id);
  await issueRis(ris._id, admin);
  assert.deepEqual((await requestableUnits()).map(unit => unit.serialNumber), ['SN-A-1'], 'Issued units disappear while other serials remain requestable');
  const par = await PAR.findOne({ ris: ris._id });
  assert.equal(par.items[0].serialNumber, 'SN-B-1');
  assert.equal(String(par.items[0].inventory), String(units[1]._id));
  assert.equal(String(par.items[0].property), String(units[1].property));
  assert.equal(par.items[0].amount, 60000);
  assert.match(par.items[0].description, /S\/N: SN-B-1/);
  const duplicate = await makeRis('RIS-DUPLICATE', units[1]._id);
  await assert.rejects(issueRis(duplicate._id, admin), /already issued or unavailable/);
  const badReceipt = await request('/iar', { ...payload, iarNumber: '1002', items: [{ ...payload.items[0], serialNumber: 'sn-b' }] });
  assert.equal(badReceipt.status, 201);
  assert.equal(badReceipt.body.data.items[0].serialNumbers[0], 'sn-b-2');
  const accepted = await request(`/custody/forms/PAR/${par._id}/accept`, {}, recipient);
  assert.equal(accepted.status, 200, JSON.stringify(accepted.body));
  const accountability = await Accountability.findOne({ ris: ris._id });
  const transfer = await request('/custody/transfers', { accountability: String(accountability._id), toUser: String(receiver._id), reason: 'Reassignment' }, recipient);
  assert.equal(transfer.status, 201, JSON.stringify(transfer.body));
  const ptr = transfer.body.data;
  assert.equal(ptr.items[0].serialNumber, 'SN-B-1');
  assert.equal(String(ptr.items[0].property), String(units[1].property));
  assert.equal((await request(`/custody/transfers/${ptr._id}/receive`, {}, receiver)).status, 200);
  const approved = await request(`/custody/transfers/${ptr._id}/approve`, {});
  assert.equal(approved.status, 200, JSON.stringify(approved.body));
  const updatedAccountability = await Accountability.findById(accountability._id);
  const transferredPar = await PAR.findById(updatedAccountability.issuanceForm);
  assert.equal(transferredPar.items[0].serialNumber, 'SN-B-1');
  assert.equal(String(transferredPar.items[0].property), String(units[1].property));
  assert.equal((await Property.findById(units[1].property)).currentCustodian.name, 'receiver Test');
  assert.equal((await PTR.findById(ptr._id)).status, 'APPROVED');
  const holders = await request('/ris/issued-items', undefined, admin, 'GET');
  assert.equal(holders.status, 200);
  assert.equal(holders.body.data.length, 1);
  assert.equal(holders.body.data[0].holders[0].name, 'receiver Test', 'Issued Items follows the current custodian after transfer');
  assert.equal(holders.body.data[0].holders[0].quantity, 1);
  assert.equal((await request('/ris/issued-items', undefined, recipient, 'GET')).status, 403);
  const cheaperRis = await makeRis('RIS-ICS-SERIAL', units[0]._id);
  await issueRis(cheaperRis._id, admin);
  const ics = await require('../src/models/InventoryCustodianSlip').findOne({ ris: cheaperRis._id });
  assert.equal(ics.items[0].serialNumber, 'SN-A-1');
  assert.equal(String(ics.items[0].property), String(units[0].property));
  assert.match(ics.items[0].description, /S\/N: SN-A-1/);
  const tooMany = await request('/iar', { ...payload, iarNumber: '1003', items: [{ ...payload.items[0], serialNumber: 'SN-C', quantity: 2 }] });
  assert.equal(tooMany.status, 201);
  assert.deepEqual(tooMany.body.data.items[0].serialNumbers, ['SN-C-1', 'SN-C-2']);
  const tooLong = await request('/iar', { ...payload, iarNumber: '1004', items: [{ ...payload.items[0], serialNumber: 'S'.repeat(19) }] });
  assert.equal(tooLong.status, 201);
  assert.equal(tooLong.body.data.items[0].serialNumbers[0], `${'S'.repeat(19)}-1`);
  const maxLength = await request('/iar', { ...payload, iarNumber: '1005', items: [{ ...payload.items[0], serialNumber: 'S'.repeat(18) }] });
  assert.equal(maxLength.status, 201, JSON.stringify(maxLength.body));
  const recordedTransfer = await PTR.create({ ptrNumber: 'PTR-RECORDED', date: '2026-10-14', fromAccountableOfficer: 'Sender', toAccountableOfficer: 'Receiver', reasonForTransfer: 'Office use', items: [{ inventory: units[0]._id, propertyNumber: units[0].propertyNumber, description: 'Laptop A', amount: 45000 }] });
  const syncTransferCard = require('../src/utils/syncTransferCard');
  await mongoose.connection.transaction(session => syncTransferCard(recordedTransfer, session));
  await mongoose.connection.transaction(session => syncTransferCard(recordedTransfer, session));
  const syncedCard = await Card.findOne({ iar: iar._id });
  const rows = syncedCard.items.filter(row => String(row.sourceDocument) === String(recordedTransfer._id));
  assert.equal(rows.length, 1, 'Saved PTR updates replace their own history entry');
  assert.equal(rows[0].sourceType, 'PTR');
  assert.equal(rows[0].itdOfficeOfficer, 'Receiver');
  assert.equal(rows[0].amount, 45000);
  assert.equal(rows[0].sourceRemarks, 'Office use');
  assert.equal(syncedCard.items.filter(row => row.receiptQuantity > 0).length, 7, 'Successive receipts share one stock-item card and remain available for exports');
  const itemLedger = await require('../src/utils/itemPropertyLedger')(units[0].item);
  assert.equal(itemLedger.summary.received, 7);
  assert.equal(itemLedger.summary.issued, 2, 'ICS, PAR and transfer forms do not deduct stock a second time');
  assert.equal(itemLedger.summary.currentBalance, 5);
  assert.equal(itemLedger.transactions.filter(row => row.type === 'Transfer').length, 2);
  assert.ok(itemLedger.transactions.filter(row => row.type === 'Transfer').every(row => row.received === 0 && row.issued === 0));
  assert.equal(itemLedger.summary.reconciliationNeeded, false);
  const bulk = await request('/iar', { ...payload, iarNumber: '1006', items: [{ ...payload.items[0], serialNumber: '', quantity: 3 }] });
  assert.equal(bulk.status, 201, JSON.stringify(bulk.body));
  assert.equal(bulk.body.data.items.length, 1, 'Quantity does not add IAR form rows');
  assert.equal(bulk.body.data.items[0].quantity, 3);
  assert.equal((await IAR.findById(bulk.body.data._id)).items.length, 1, 'Reopening the IAR retains the entered row count');
  const bulkUnits = await Inventory.find({ inspectionAcceptanceReport: bulk.body.data._id });
  assert.equal(bulkUnits.length, 3);
  assert.ok(bulkUnits.every(unit => unit.quantity === 1));
  assert.equal(new Set(bulkUnits.map(unit => unit.propertyNumber)).size, 3);
  assert.equal(new Set(bulkUnits.map(unit => String(unit.property))).size, 3);
  assert.equal(await Card.countDocuments({ stockItem: units[0].item }), 1);
  const updatedLedger = await require('../src/utils/itemPropertyLedger')(units[0].item);
  assert.equal(updatedLedger.summary.received, 10);
  assert.equal(updatedLedger.summary.currentBalance, 8);
  const returned = await request(`/users/${receiver._id}/records/returned`, { accountability: String(updatedAccountability._id), quantity: 1, condition: 'Serviceable' });
  assert.equal(returned.status, 201, JSON.stringify(returned.body));
  assert.ok((await requestableUnits()).some(unit => String(unit._id) === String(units[1]._id)), 'The same serviceable returned serial becomes available again');
  assert.equal((await require('../src/utils/itemPropertyLedger')(units[0].item)).summary.currentBalance, 9);
  const duplicateReturn = await request(`/users/${receiver._id}/records/returned`, { accountability: String(updatedAccountability._id), quantity: 1, condition: 'Serviceable' });
  assert.equal(duplicateReturn.status, 409);
  const reissued = await makeRis('RIS-RETURNED-UNIT', units[1]._id);
  await issueRis(reissued._id, admin);
  assert.ok(!(await requestableUnits()).some(unit => String(unit._id) === String(units[1]._id)));
  const cheaperAccountability = await Accountability.findOne({ ris: cheaperRis._id });
  const damaged = await request(`/users/${recipient._id}/records/returned`, { accountability: String(cheaperAccountability._id), quantity: 1, condition: 'Unserviceable' });
  assert.equal(damaged.status, 201, JSON.stringify(damaged.body));
  assert.ok(!(await requestableUnits()).some(unit => String(unit._id) === String(units[0]._id)), 'Unserviceable returns never enter requestable stock');
  assert.equal((await require('../src/utils/itemPropertyLedger')(units[0].item)).summary.currentBalance, 8);
  const batch = await RIS.create({ risNumber: 'RIS-MULTIPLE-ASSETS', status: 'APPROVED', requestedBy: { user: recipient._id, name: 'recipient Test' }, items: [{ stockNumber: 'LAPTOP', inventory: bulkUnits[0]._id, description: 'Laptop', quantityRequested: 3, quantityIssued: 2 }] });
  await issueRis(batch._id, admin);
  const batchIssued = await RIS.findById(batch._id);
  assert.equal(batchIssued.items.length, 2);
  const batchAccounts = await Accountability.find({ ris: batch._id });
  assert.equal(batchAccounts.length, 2, 'Each asset receives its own accountability');
  assert.equal(new Set(batchAccounts.map(row => String(row.inventory))).size, 2);
  for (const row of batchIssued.items) {
    const physicalUnit = await Inventory.findById(row.inventory);
    assert.equal(String(row.property), String(physicalUnit.property));
    assert.equal(row.serialNumber, physicalUnit.serialNumber);
    assert.equal(row.totalCost, physicalUnit.unitCost);
    assert.equal(row.quantityIssued, 1);
  }
  assert.equal((await require('../src/utils/itemPropertyLedger')(units[0].item)).summary.currentBalance, 6);
  const availableForRepair = (await requestableUnits())[0];
  const legacy = await RIS.create({ risNumber: 'RIS-LEGACY-UNDERISSUED', status: 'APPROVED', requestedBy: { user: recipient._id, name: 'recipient Test' }, items: [{ stockNumber: 'LAPTOP', inventory: availableForRepair._id, description: 'Laptop', quantityRequested: 6, quantityIssued: 1 }] });
  await issueRis(legacy._id, admin, {}, { silent: true });
  const beforeRepair = await RIS.findById(legacy._id);
  const originalAccount = beforeRepair.items[0].accountability;
  const originalForm = beforeRepair.items[0].issuanceForm;
  await issueRis(legacy._id, admin, {}, { completeQuantity: { lineId: beforeRepair.items[0]._id, target: 6 }, silent: true });
  const repaired = await RIS.findById(legacy._id);
  assert.equal(repaired.items.reduce((sum, row) => sum + row.quantityIssued, 0), 6);
  assert.equal(repaired.items.reduce((sum, row) => sum + row.quantityRequested, 0), 6);
  assert.equal(new Set(repaired.items.map(row => String(row.inventory))).size, 6);
  assert.equal(String(repaired.items[0].accountability), String(originalAccount));
  assert.equal(String(repaired.items[0].issuanceForm), String(originalForm));
  assert.equal(await Accountability.countDocuments({ ris: legacy._id }), 6);
  const correctedLedger = await require('../src/utils/itemPropertyLedger')(units[0].item);
  assert.equal(correctedLedger.summary.currentBalance, 0);
  assert.equal(correctedLedger.summary.reconciliationNeeded, false);
  assert.equal(correctedLedger.transactions.filter(row => row.source?.id === String(legacy._id)).reduce((sum, row) => sum + row.issued, 0), 6);
  await assert.rejects(issueRis(legacy._id, admin, {}, { completeQuantity: { lineId: beforeRepair.items[0]._id, target: 6 }, silent: true }), /original under-issued/);
  assert.equal((await require('../src/models/Item').findById(units[0].item)).quantityOnHand, 0);
  const reportList = await request('/ris', undefined, admin, 'GET');
  assert.equal(reportList.status, 200);
  const reportCard = reportList.body.data.find(row => row._id === String(legacy._id));
  assert.deepEqual(reportCard.itemNames, ['IT Equipment'], 'Report headings use one item name instead of serial-unit descriptions');
  assert.equal(reportCard.requestedBy.name, 'recipient Test');
  const pagedReports = await request('/ris?page=1&limit=1', undefined, admin, 'GET');
  assert.equal(pagedReports.status, 200);
  assert.ok(Array.isArray(pagedReports.body.data.items[0].itemNames));
});
