const test = require('node:test');
const assert = require('node:assert/strict');
const path = require('node:path');
const mongoose = require('mongoose');
const jwt = require('jsonwebtoken');
const { MongoMemoryReplSet } = require('mongodb-memory-server');
const User = require('../src/models/User');
const IAR = require('../src/models/InspectionAcceptanceReport');
const Inventory = require('../src/models/Inventory');
const Item = require('../src/models/Item');
const RIS = require('../src/models/RequisitionIssueSlip');
const Card = require('../src/models/PropertyCard');
const Sequence = require('../src/models/DocumentSequence');

test('one IAR supply row generates numbered serials per accepted unit without a character limit', { timeout: 90000 }, async t => {
 const database = await MongoMemoryReplSet.create({ replSet: { count: 1 }, binary: { systemBinary: path.resolve(__dirname, '../node_modules/.cache/mongodb-memory-server/mongod-x64-win32-8.2.6.exe') } });
 await mongoose.connect(database.getUri());
 await Promise.all([IAR, Inventory, Item, RIS, Card, Sequence].map(Model => Model.init()));
 await require('../src/models/Setting').create({ entityName: 'Carigara' });
 const server = require('../src/app').listen(0);
 t.after(async () => { server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); await mongoose.disconnect(); await database.stop(); });
 const admin = await User.create({ username: 'admin', firstName: 'Admin', lastName: 'Test', email: 'admin@example.test', password: 'test', office: 'Supply', division: 'Finance', role: 'admin' });
 const form = (number, serial, quantity, key) => ({ submissionKey: key, entityName: 'Carigara', fundCluster: 'General Fund', supplierName: 'Supplier', poNumber: 'PO-1', poDate: '2026-10-14', responsibilityCenterCode: 'Supply', iarNumber: number, iarDate: '2026-10-14', invoiceNumber: 'INV-1', invoiceDate: '2026-10-14', inspectionDate: '2026-10-14', inspectedBy: 'Inspector', acceptanceDate: '2026-10-14', custodian: 'Custodian', items: [{ stockPropertyNumber: 'PAPER', propertyPlantAndEquipment: 'Bondpaper', itemType: 'SUPPLY', description: 'A4 paper', unit: 'ream', quantity, unitCost: 200, serialNumber: serial }] });
 const save = async payload => {
  const response = await fetch(`http://127.0.0.1:${server.address().port}/api/iar`, { method: 'POST', headers: { Authorization: `Bearer ${jwt.sign({ id: admin._id }, process.env.JWT_SECRET || 'dev-secret')}`, 'Content-Type': 'application/json' }, body: JSON.stringify(payload) });
  const body = await response.json(); assert.ok([200, 201].includes(response.status), JSON.stringify(body)); return body.data;
 };
 const firstForm = form('1001', '45241', 10, 'serial-receipt-0001');
 const first = await save(firstForm);
 assert.equal(first.items.length, 1); assert.equal(first.items[0].quantity, 10); assert.equal(first.items[0].serialNumber, '45241');
 assert.deepEqual(first.items[0].serialNumbers, Array.from({ length: 10 }, (_, index) => `45241-${index + 1}`));
 const units = await Inventory.find({ inspectionAcceptanceReport: first._id }).sort({ createdAt: 1, _id: 1 });
 assert.equal(units.length, 10); assert.ok(units.every(unit => unit.quantity === 1));
 assert.equal(new Set(units.map(unit => unit.serialNumber)).size, 10);
 assert.equal(await RIS.countDocuments({ iar: first._id }), 0, 'IAR receipts must not create RIS drafts');
 const replay = await save(firstForm); assert.equal(replay._id, first._id);
 const second = await save(form('1002', '45241', 2, 'serial-receipt-0002'));
 assert.deepEqual(second.items[0].serialNumbers, ['45241-11', '45241-12']);
 const longBase = 'Very long / serial + characters [] .* # - '.repeat(4);
 const long = await save(form('1003', longBase, 2, 'serial-receipt-0003'));
 assert.deepEqual(long.items[0].serialNumbers, [`${longBase.trim()}-1`, `${longBase.trim()}-2`]);
 const parallel = await Promise.all([save(form('1004', '45241', 1, 'serial-receipt-0004')), save(form('1005', '45241', 1, 'serial-receipt-0005'))]);
 assert.deepEqual(parallel.flatMap(doc => doc.items[0].serialNumbers).sort(), ['45241-13', '45241-14']);
 const stock = await Item.findOne({ stockNumber: 'PAPER' }); assert.equal(stock.quantityOnHand, 16);
 assert.equal(await Card.countDocuments({ stockItem: stock._id }), 1);
 const partialForm = form('1006', 'PARTIAL', 5, 'serial-receipt-0006'); partialForm.acceptanceStatus = 'Partial'; partialForm.acceptanceQuantity = 2;
 const partial = await save(partialForm);
 assert.equal(partial.items[0].quantity, 5); assert.deepEqual(partial.items[0].serialNumbers, ['PARTIAL-1', 'PARTIAL-2']);
 assert.equal((await Item.findById(stock._id)).quantityOnHand, 18);
 const recipient = await User.create({ username: 'borrower', firstName: 'Borrower', lastName: 'Test', email: 'borrower@example.test', password: 'test', office: 'Supply', division: 'Finance', role: 'user', permissions: ['canViewRIS'] });
 const unit = units[0];
 const ris = await RIS.create({ risNumber: 'RIS-SERIAL-PAPER', status: 'APPROVED', office: 'Supply', requestedBy: { user: recipient._id, name: 'Borrower Test' }, items: [{ inventory: unit._id, stockNumber: 'PAPER', description: 'Bondpaper', unit: 'ream', quantityRequested: 1, quantityIssued: 1 }] });
 const issue = require('../src/utils/issueRis');
 await issue(ris._id, admin);
 const api = async (url, body) => {
   const response = await fetch(`http://127.0.0.1:${server.address().port}/api${url}`, { method: body ? 'POST' : 'GET', headers: { Authorization: `Bearer ${jwt.sign({ id: admin._id }, process.env.JWT_SECRET || 'dev-secret')}`, 'Content-Type': 'application/json' }, ...(body ? { body: JSON.stringify(body) } : {}) });
   return { status: response.status, data: await response.json() };
 };
 const available = async () => (await api('/ris/request-items')).data.data.flatMap(item => item.units);
 assert.equal((await Item.findById(stock._id)).quantityOnHand, 17);
 const holders = await api('/ris/issued-items');
 assert.equal(holders.status, 200);
 assert.equal(holders.data.data[0].name, 'Bondpaper');
 assert.equal(holders.data.data[0].holders[0].name, 'Borrower Test');
 assert.equal(holders.data.data[0].holders[0].quantity, 1);
 assert.ok(!(await available()).some(row => String(row._id) === String(unit._id)), 'Serialized supplies are hidden even when other units of that item remain in stock');
 const competing = await RIS.create({ risNumber: 'RIS-SERIAL-PAPER-DUPLICATE', status: 'APPROVED', requestedBy: { user: recipient._id, name: 'Borrower Test' }, items: [{ inventory: unit._id, stockNumber: 'PAPER', description: 'Bondpaper', quantityRequested: 1, quantityIssued: 1 }] });
 await assert.rejects(issue(competing._id, admin), /already issued or unavailable/);
 const issued = await RIS.findById(ris._id);
 const returned = await api(`/users/${recipient._id}/records/returned`, { risId: String(issued._id), itemId: String(issued.items[0]._id), quantity: 1, condition: 'Serviceable' });
 assert.equal(returned.status, 201, JSON.stringify(returned.data));
 assert.equal((await Item.findById(stock._id)).quantityOnHand, 18);
 assert.equal((await api('/ris/issued-items')).data.data.length, 0, 'Fully returned supplies leave the current holder list');
 assert.ok((await available()).some(row => String(row._id) === String(unit._id)), 'A serviceable supply return restores its original serial, not a different unit');
 const multiple = await RIS.create({ risNumber: 'RIS-MULTIPLE-SERIAL-PAPER', status: 'APPROVED', requestedBy: { user: recipient._id, name: 'Borrower Test' }, items: [{ inventory: unit._id, stockNumber: 'PAPER', description: 'Bondpaper', quantityRequested: 5, quantityIssued: 3 }] });
 assert.equal(multiple.items.length, 1, 'Requested quantities remain on a single editable draft row');
 await issue(multiple._id, admin);
 const issuedMultiple = await RIS.findById(multiple._id);
 assert.equal(issuedMultiple.items.length, 3);
 assert.equal(new Set(issuedMultiple.items.map(row => String(row.inventory))).size, 3);
 assert.equal(new Set(issuedMultiple.items.map(row => row.serialNumber)).size, 3);
 assert.equal(issuedMultiple.items.reduce((sum, row) => sum + row.quantityRequested, 0), 5);
 assert.equal(issuedMultiple.items.reduce((sum, row) => sum + row.quantityIssued, 0), 3);
 assert.equal((await Item.findById(stock._id)).quantityOnHand, 15);
 const batchHolders = (await api('/ris/issued-items')).data.data;
 assert.equal(batchHolders.length, 1);
 assert.equal(batchHolders[0].holders.length, 1);
 assert.equal(batchHolders[0].holders[0].quantity, 3);
 await issue(multiple._id, admin, {}, { approve: true });
 assert.equal((await Item.findById(stock._id)).quantityOnHand, 15, 'Approval retries do not deduct multiple units twice');
 const remainingUnit = (await available())[0];
 const tooMany = await RIS.create({ risNumber: 'RIS-INSUFFICIENT-SERIALS', status: 'APPROVED', requestedBy: { user: recipient._id, name: 'Borrower Test' }, items: [{ inventory: remainingUnit._id, stockNumber: 'PAPER', description: 'Bondpaper', quantityRequested: 100, quantityIssued: 100 }] });
 await assert.rejects(issue(tooMany._id, admin), /Insufficient available units/);
 assert.equal((await Item.findById(stock._id)).quantityOnHand, 15);
 assert.equal((await RIS.findById(tooMany._id)).status, 'APPROVED');
 const twentyForm = form('1007', 'QTY-TEST', 20, 'serial-receipt-0007');
 twentyForm.items[0].stockPropertyNumber = 'QTY20';
 const twentyReceipt = await save(twentyForm);
 const twentyStock = await Item.findOne({ stockNumber: 'QTY20' });
 const firstUnit = await Inventory.findOne({ inspectionAcceptanceReport: twentyReceipt._id });
 const three = await RIS.create({ risNumber: 'RIS-TWENTY-REQUEST-THREE', status: 'PENDING_REVIEW', requestedBy: { user: recipient._id, name: 'Borrower Test' }, items: [{ inventory: firstUnit._id, stockNumber: 'QTY20', description: 'Bondpaper', quantityRequested: 3, quantityIssued: 3 }] });
 assert.equal((await Item.findById(twentyStock._id)).quantityOnHand, 20, 'Pending request leaves all twenty units available');
 await issue(three._id, admin, {}, { approve: true });
 assert.equal((await Item.findById(twentyStock._id)).quantityOnHand, 17);
 const twentyLedger = await require('../src/utils/itemPropertyLedger')(twentyStock._id);
 assert.equal(twentyLedger.summary.received, 20);
 assert.equal(twentyLedger.summary.issued, 3);
 assert.equal(twentyLedger.summary.currentBalance, 17);
 assert.equal(twentyLedger.summary.reconciliationNeeded, false);
 const threeIssued = await RIS.findById(three._id);
 assert.equal(new Set(threeIssued.items.map(row => row.serialNumber)).size, 3);
});
