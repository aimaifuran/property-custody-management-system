const test = require('node:test');
const assert = require('node:assert/strict');
const path = require('node:path');
const mongoose = require('mongoose');
const jwt = require('jsonwebtoken');
const { MongoMemoryReplSet } = require('mongodb-memory-server');
const User = require('../src/models/User');
const { lockInactiveUsers } = require('../src/utils/inactivityLock');

test('60-day inactivity locks users, denies access and allows an admin unlock grace period', { timeout: 90000 }, async t => {
  const database = await MongoMemoryReplSet.create({ replSet: { count: 1 }, binary: { systemBinary: path.resolve(__dirname, '../node_modules/.cache/mongodb-memory-server/mongod-x64-win32-8.2.6.exe') } });
  await mongoose.connect(database.getUri());
  const server = require('../src/app').listen(0);
  t.after(async () => { server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); await mongoose.disconnect(); await database.stop(); });
  const now = new Date();
  const ago = days => new Date(now.getTime() - days * 86400000);
  const create = (username, extra = {}) => User.create({ username, firstName: username, lastName: 'Test', email: `${username}@example.test`, password: 'test', office: 'Supply', division: 'Supply', ...extra });
  const admin = await create('admin', { role: 'admin', lastLogin: ago(90) });
  const stale = await create('stale', { lastLogin: ago(60), refreshToken: 'old-session' });
  const recent = await create('recent', { lastLogin: ago(59) });
  const never = await create('never', { createdAt: ago(61) });
  await lockInactiveUsers({}, now);
  assert.equal((await User.findById(stale._id)).locked, true);
  assert.equal((await User.findById(stale._id)).refreshToken, undefined);
  assert.equal((await User.findById(never._id)).locked, true);
  assert.equal((await User.findById(recent._id)).locked, false);
  assert.equal((await User.findById(admin._id)).locked, false);
  const request = (actor, route, method = 'GET', body) => fetch(`http://127.0.0.1:${server.address().port}/api${route}`, { method, headers: { Authorization: `Bearer ${jwt.sign({ id: actor._id }, process.env.JWT_SECRET || 'dev-secret')}`, 'Content-Type': 'application/json' }, ...(body ? { body: JSON.stringify(body) } : {}) });
  assert.equal((await request(stale, '/auth/me')).status, 401);
  assert.equal((await request(admin, `/users/${stale._id}/lock`, 'PATCH', { locked: false })).status, 200);
  await lockInactiveUsers();
  const unlocked = await User.findById(stale._id);
  assert.equal(unlocked.locked, false);
  assert.ok(unlocked.inactivityResetAt);
  assert.equal(unlocked.lastLogin.getTime(), stale.lastLogin.getTime(), 'Unlock does not fabricate a login');
  assert.equal((await request(stale, '/auth/me')).status, 200);
  await lockInactiveUsers({ _id: stale._id }, new Date(unlocked.inactivityResetAt.getTime() + 60 * 86400000));
  assert.equal((await User.findById(stale._id)).locked, true, 'Grace period also expires after 60 days');
  await User.updateOne({ _id: recent._id }, { $set: { lastLogin: ago(61) } });
  assert.equal((await request(recent, '/auth/me')).status, 401, 'Authentication enforces inactivity without visiting the directory');
});
