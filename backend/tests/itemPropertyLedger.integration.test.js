const test = require('node:test');
const assert = require('node:assert/strict');
const path = require('node:path');
const mongoose = require('mongoose');
const jwt = require('jsonwebtoken');
const { MongoMemoryReplSet } = require('mongodb-memory-server');
const Item = require('../src/models/Item');
const Inventory = require('../src/models/Inventory');
const IAR = require('../src/models/InspectionAcceptanceReport');
const RIS = require('../src/models/RequisitionIssueSlip');
const PRS = require('../src/models/PropertyReturnSlip');
const Card = require('../src/models/PropertyCard');
const Ledger = require('../src/models/LedgerTransaction');
const User = require('../src/models/User');
const issueRis = require('../src/utils/issueRis');
const postReturn = require('../src/utils/postPropertyReturn');
const itemPropertyLedger = require('../src/utils/itemPropertyLedger');

test('item card uses accepted receipts, actual issues and eligible returns once across source forms', { timeout: 90000 }, async t => {
  const database = await MongoMemoryReplSet.create({ replSet: { count: 1 }, binary: { systemBinary: path.resolve(__dirname, '../node_modules/.cache/mongodb-memory-server/mongod-x64-win32-8.2.6.exe') } });
  await mongoose.connect(database.getUri());
  await Promise.all([IAR, RIS, PRS, Card, Ledger, Inventory, Item].map(Model => Model.init()));
  await require('../src/models/Setting').create({ entityName: 'Carigara' });
  const server = require('../src/app').listen(0);
  t.after(async () => { server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); await mongoose.disconnect(); await database.stop(); });
  const makeUser = (name, role) => User.create({ username: name, firstName: name, lastName: 'Test', email: `${name}@example.test`, password: 'test', role, office: 'Treasury', division: 'Finance', permissions: ['canViewRIS'] });
  const admin = await makeUser('admin', 'admin'), recipient = await makeUser('recipient', 'user');
  const request = async (url, body, actor = admin, method = 'POST') => {
    const response = await fetch(`http://127.0.0.1:${server.address().port}/api${url}`, { method, headers: { Authorization: `Bearer ${jwt.sign({ id: actor._id }, process.env.JWT_SECRET || 'dev-secret')}`, 'Content-Type': 'application/json' }, ...(body ? { body: JSON.stringify(body) } : {}) });
    return { status: response.status, body: await response.json() };
  };
  const form = (number, quantity) => ({ entityName: 'Carigara', fundCluster: 'General Fund', supplierName: 'Supplier', poNumber: 'PO-1', poDate: '2026-10-14', responsibilityCenterCode: 'Supply', iarNumber: number, iarDate: '2026-10-14', invoiceNumber: 'INV-1', invoiceDate: '2026-10-14', inspectionDate: '2026-10-14', inspectedBy: 'Inspector', acceptanceDate: '2026-10-14', custodian: 'Custodian', items: [{ stockPropertyNumber: 'PAPER', itemType: 'SUPPLY', description: 'Bond paper', unit: 'ream', quantity, unitCost: 200 }] });
  const receipt = form('1001', 10); receipt.submissionKey = 'receipt-submission-0001';
  assert.equal((await request('/iar', receipt)).status, 201);
  assert.equal((await request('/iar', receipt)).status, 200);
  let stock = await Item.findOne({ stockNumber: 'PAPER' });
  assert.equal(stock.quantityOnHand, 10);
  assert.equal(await Ledger.countDocuments(), 1);
  const partial = form('1002', 5); partial.acceptanceStatus = 'Partial'; partial.acceptanceQuantity = 2; partial.items[0].acceptedQuantity = 2;
  assert.equal((await request('/iar', partial)).status, 201);
  stock = await Item.findById(stock._id);
  assert.equal(stock.quantityOnHand, 12);
  assert.equal(await Card.countDocuments({ stockItem: stock._id }), 1, 'All receipts share the stock item card');
  assert.equal((await request('/iar', { ...form('1003', 100), status: 'REJECTED' })).status, 400);
  assert.equal((await request('/iar', { ...form('1004', 100), status: 'PENDING_INSPECTION' })).status, 400);
  assert.equal((await Item.findById(stock._id)).quantityOnHand, 12);
  const pending = await RIS.create({ risNumber: 'RIS-PENDING', status: 'PENDING_REVIEW', requestedBy: { user: recipient._id, name: 'recipient Test' }, items: [{ stockNumber: 'PAPER', unit: 'ream', description: 'Bond paper', quantityRequested: 5, quantityIssued: 3 }] });
  assert.equal((await itemPropertyLedger(stock._id)).summary.currentBalance, 12);
  pending.status = 'APPROVED'; await pending.save();
  await issueRis(pending._id, admin);
  assert.equal((await Item.findById(stock._id)).quantityOnHand, 9);
  await issueRis(pending._id, admin, {}, { approve: true });
  assert.equal((await Item.findById(stock._id)).quantityOnHand, 9);
  const issued = await RIS.findById(pending._id);
  const unfilled = await RIS.create({ risNumber: 'RIS-NO-ACTUAL', status: 'APPROVED', requestedBy: { user: recipient._id, name: 'recipient Test' }, items: [{ stockNumber: 'PAPER', description: 'Bond paper', quantityRequested: 2 }] });
  await assert.rejects(issueRis(unfilled._id, admin), /actual issued quantity/);
  const returnForm = condition => PRS.create({ prsNumber: `PRS-${condition}`, status: 'RETURNED', returnedBy: { user: recipient._id, name: 'recipient Test', designation: 'Treasury' }, returnedTo: { name: 'Admin', date: new Date() }, items: [{ ris: issued._id, risItem: issued.items[0]._id, condition, quantity: 1, unit: 'ream', description: 'Bond paper', unitValue: 200 }] });
  const serviceable = await returnForm('Serviceable');
  await mongoose.connection.transaction(session => postReturn(serviceable, session));
  await mongoose.connection.transaction(session => postReturn(serviceable, session));
  const damaged = await returnForm('Unserviceable');
  await mongoose.connection.transaction(session => postReturn(damaged, session));
  const result = await itemPropertyLedger(stock._id);
  assert.deepEqual(result.summary, { openingBalance: 0, received: 12, issued: 3, returned: 1, adjustments: 0, currentBalance: 10, availableStock: 10, reconciliationNeeded: false, lastMovement: result.summary.lastMovement });
  assert.deepEqual(result.transactions.map(row => row.balance), [10, 12, 9, 10, 10]);
  assert.ok(result.transactions.every(row => row.source && row.source.href.includes('?record=')));
  assert.equal(result.relatedDocuments.filter(doc => doc.type === 'IAR').length, 2);
  assert.equal(result.transactions.filter(row => row.source?.number === 'RIS-PENDING').length, 1);
  await Item.updateOne({ _id: stock._id }, { $set: { reorderLevel: 11 } });
  const list = await request('/property-cards/stock-ledger', undefined, admin, 'GET');
  assert.equal(list.status, 200);
  assert.equal(list.body.data.summary.total, 1);
  assert.equal(list.body.data.summary.lowStock, 1);
  assert.equal(list.body.data.items[0].stockStatus, 'Low Stock');
  const detail = await request(`/property-cards/stock-ledger/${stock._id}`, undefined, admin, 'GET');
  assert.equal(detail.status, 200);
  assert.equal(detail.body.data.summary.currentBalance, 10);
  assert.equal((await request('/property-cards/stock-ledger', undefined, recipient, 'GET')).status, 403);
  assert.equal((await request('/items', { stockNumber: 'UNPOSTED', description: 'Invalid opening', unit: 'unit', quantityOnHand: 100 })).status, 400);
  await Item.updateOne({ _id: stock._id }, { $set: { quantityOnHand: 9 } });
  const mismatch = await itemPropertyLedger(stock._id);
  assert.equal(mismatch.summary.reconciliationNeeded, true);
  assert.equal(mismatch.summary.currentBalance, 10, 'History is not silently rewritten to match an incorrect balance');
  await Item.updateOne({ _id: stock._id }, { $set: { quantityOnHand: 10 } });
  const movement = await Ledger.findOne().lean(); delete movement._id;
  await assert.rejects(Ledger.create(movement), error => error.code === 11000);
  // Latest receipt controls the item list before pagination; replenishment reuses the item.
  const inkReceipt = form('1003', 5);
  inkReceipt.items[0] = { ...inkReceipt.items[0], stockPropertyNumber: 'INK', propertyPlantAndEquipment: 'Ink', description: 'Black ink' };
  assert.equal((await request('/iar', inkReceipt)).status, 201);
  let recent = await request('/property-cards/stock-ledger?limit=1', undefined, admin, 'GET');
  assert.equal(recent.body.data.items[0].stockNumber, 'INK');
  assert.equal(recent.body.data.items[0].isNew, true);
  assert.equal(recent.body.data.pagination.total, 2);
  const alphabetical = await request('/property-cards/stock-ledger?sort=name&limit=1', undefined, admin, 'GET');
  assert.equal(alphabetical.body.data.items[0].stockNumber, 'PAPER');
  assert.equal((await request('/iar', form('1004', 1))).status, 201);
  recent = await request('/property-cards/stock-ledger', undefined, admin, 'GET');
  assert.equal(recent.body.data.items[0].stockNumber, 'PAPER');
  assert.equal(recent.body.data.items[0].quantityOnHand, 11);
  assert.equal(recent.body.data.items.filter(row => row.stockNumber === 'PAPER').length, 1);
  const history = await itemPropertyLedger(stock._id);
  assert.ok(history.transactions.every((row, index, rows) => !index || new Date(rows[index - 1].date) <= new Date(row.date)), 'Card history remains chronological');

});
