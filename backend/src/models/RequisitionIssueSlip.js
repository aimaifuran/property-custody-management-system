const mongoose = require('mongoose');

const requisitionIssueSlipSchema = new mongoose.Schema({
  manualIssueKey: { type: String, unique: true, sparse: true },
  sourceInventory: { type: mongoose.Schema.Types.ObjectId, ref: 'Inventory' },
  iar: { type: mongoose.Schema.Types.ObjectId, ref: 'InspectionAcceptanceReport', index: true },
  risNumber: { type: String, unique: true, sparse: true, trim: true },
  entityName: { type: String },
  fundCluster: { type: String },
  division: { type: String },
  office: { type: String },
  responsibilityCenterCode: { type: String },
  purpose: { type: String },
  requestedBy: {
    offlineRecipient: { type: mongoose.Schema.Types.ObjectId, ref: 'OfflineRecipient', index: true },
    user: { type: mongoose.Schema.Types.ObjectId, ref: 'User', index: true },
    name: { type: String, trim: true },
    designation: { type: String, trim: true },
    date: { type: Date },
  },
  approvedBy: {
    name: { type: String, trim: true },
    designation: { type: String, trim: true },
    date: { type: Date },
  },
  issuedBy: {
    name: { type: String, trim: true },
    designation: { type: String, trim: true },
    date: { type: Date },
  },
  receivedBy: {
    offlineRecipient: { type: mongoose.Schema.Types.ObjectId, ref: 'OfflineRecipient', index: true },
    user: { type: mongoose.Schema.Types.ObjectId, ref: 'User', index: true },
    name: { type: String, trim: true },
    designation: { type: String, trim: true },
    date: { type: Date },
  },
  date: { type: Date },
  status: {
    type: String,
    enum: ['PENDING_REVIEW', 'REVIEWED', 'PENDING_APPROVAL', 'APPROVED', 'ISSUED', 'ACCOUNTABILITY_LOCKED', 'REJECTED', 'DRAFT'],
    default: 'PENDING_REVIEW',
  },
  rejectionReason: { type: String },
  rejectedBy: { type: String },
  reviewedBy: { type: String },
  reviewedAt: { type: Date },
  approvedAt: { type: Date },
  rejectedAt: { type: Date },
  issuedAt: { type: Date },
  inventoryCustodianSlip: { type: mongoose.Schema.Types.ObjectId, ref: 'InventoryCustodianSlip' },
  propertyAcknowledgementReceipt: { type: mongoose.Schema.Types.ObjectId, ref: 'PropertyAcknowledgementReceipt' },
  signatureHash: { type: String },
  returnRevision: { type: Number, default: 0 },
  items: [{
    inventory: { type: mongoose.Schema.Types.ObjectId, ref: 'Inventory' },
    property: { type: mongoose.Schema.Types.ObjectId, ref: 'Property' },
    serialNumber: { type: String, trim: true },
    itemName: { type: String, trim: true },
    fundCluster: { type: String, trim: true },
    responsibilityCenterCode: { type: String, trim: true },
    stockNumber: { type: String, default: null },
    unit: String,
    description: String,
    quantityRequested: Number,
    stockAvailable: Number,
    isAvailable: Boolean,
    quantityIssued: Number,
    totalCost: Number,
    remarks: String,
    unitCost: Number,
    formType: { type: String, enum: ['ICS', 'PAR', 'SUPPLY'] },
    documentNumber: String,
    issuanceForm: mongoose.Schema.Types.ObjectId,
    accountability: { type: mongoose.Schema.Types.ObjectId, ref: 'PropertyAccountability' },
  }],
  totalQuantity: { type: Number, default: 0 },
  deleted: { type: Boolean, default: false },
  lastEditedAt: Date,
}, { timestamps: true });

module.exports = mongoose.model('RequisitionIssueSlip', requisitionIssueSlipSchema);
